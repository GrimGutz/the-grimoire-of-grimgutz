function description(body, automation) {
  return `${body}<hr><p><strong>Автоматизация Foundry:</strong> ${automation}</p>`;
}

function longRestUse(max = "1") {
  return {
    max,
    spent: 0,
    recovery: [{ period: "lr", type: "recoverAll" }]
  };
}

function shortRestUse(max = "1") {
  return {
    max,
    spent: 0,
    recovery: [
      { period: "sr", type: "recoverAll" },
      { period: "lr", type: "recoverAll" }
    ]
  };
}

function spiritVesselFeature({
  key,
  name,
  img,
  level,
  description: value,
  activities = {},
  uses = null,
  folderId = MAIN_FOLDER,
  automation = {}
}) {
  return feature({
    key,
    name,
    img,
    level,
    requirements: `Сосуд Духа ${level}`,
    folder: folderId,
    uses,
    activities,
    automation: {
      feature: key,
      spiritVesselFeature: true,
      minimumLevel: level,
      ...automation
    },
    sourcePage: "1–5",
    sourceCustom: SOURCE,
    description: value
  });
}

function strikeActivity(slotLevel) {
  const dice = Math.min(5, 1 + Number(slotLevel));
  return utilityActivity({
    key: `spirit-vessel-concentrated-strike-${slotLevel}`,
    name: `Концентрированный удар: ячейка ${slotLevel}`,
    action: "roll-spirit-vessel-concentrated-strike",
    actionData: { slotLevel, dice },
    activation: "special",
    condition: "После попадания атакой ближнего боя, дальнобойной атакой или заклинанием",
    spellSlot: false
  });
}

function spiritFeature({
  key,
  name,
  spirit,
  img,
  body,
  automation,
  activities = {},
  uses = null
}) {
  return spiritVesselFeature({
    key,
    name,
    img,
    level: 1,
    folderId: SPIRIT_FOLDER,
    uses,
    activities,
    automation: {
      spiritVesselSpirit: spirit
    },
    description: description(body, automation)
  });
}

