function description(body, automation) {
  return `${body}<hr><p><strong>Автоматизация Foundry:</strong> ${automation}</p>`;
}

function crusaderFeature({
  key,
  name,
  img,
  level,
  description: value,
  uses = null,
  activities = {},
  effects = [],
  automation = {}
}) {
  return feature({
    key,
    name,
    img,
    level,
    requirements: `Крестоносец ${level}`,
    folder: MAIN_FOLDER,
    uses,
    activities,
    effects,
    automation: {
      feature: key,
      crusaderFeature: true,
      minimumLevel: level,
      ...automation
    },
    sourcePage: "1–2",
    sourceCustom: SOURCE,
    description: value
  });
}

