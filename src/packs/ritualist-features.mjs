function longRestUse(max = "1") {
  return {
    max,
    spent: 0,
    recovery: [
      { period: "lr", type: "recoverAll" }
    ]
  };
}

function shortOrLongRestUse(max = "1") {
  return {
    max,
    spent: 0,
    recovery: [
      { period: "sr", type: "recoverAll" },
      { period: "lr", type: "recoverAll" }
    ]
  };
}

function description(body, automation) {
  return `
    ${body}
    <hr>
    <p><strong>Автоматизация Foundry:</strong> ${automation}</p>
  `;
}

function ritualistFeature({
  key,
  name,
  img,
  level,
  description: value,
  uses = null,
  activities = {},
  extraAutomation = {}
}) {
  return feature({
    key,
    name,
    img,
    level,
    requirements: `Ритуалист ${level}`,
    folder: MAIN_FOLDER,
    uses,
    activities,
    automation: {
      feature: key,
      ritualistFeature: true,
      minimumLevel: level,
      ...extraAutomation
    },
    sourcePage: "1–3",
    sourceCustom: SOURCE,
    description: value
  });
}

function ritualPointActivity({ key, name, cost, activation = "action" }) {
  return utilityActivity({
    key,
    name,
    action: "summon-ritualist-spirits",
    actionData: cost ? { ritualistRitualPointCost: cost } : {},
    activation,
    spellSlot: false
  });
}

function spiritRollActivity({ key, name, action, activation = "special" }) {
  return utilityActivity({
    key,
    name,
    action,
    activation,
    spellSlot: false,
    targetType: "creature",
    targetCount: "1",
    targetChoice: true
  });
}

