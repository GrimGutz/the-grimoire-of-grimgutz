const MAIN_FOLDER = idFor("folder:keeper-features");
const SPECIALIZATION_FOLDER = idFor("folder:keeper-specializations");

export const keeperFolders = [
  folder({ key: "keeper-features", name: "Хранитель: классовые особенности", sort: 1090000 }),
  folder({ key: "keeper-specializations", name: "Хранитель: специализации", sort: 1091000 })
];

function description(body, automation) {
  return `
    ${body}
    <hr>
    <p><strong>Автоматизация Foundry:</strong> ${automation}</p>
  `;
}

function keeperFeature({
  key,
  name,
  img,
  level,
  description: value,
  uses = null,
  activities = {},
  folder = MAIN_FOLDER,
  extraAutomation = {}
}) {
  return feature({
    key,
    name,
    img,
    level,
    requirements: `Хранитель ${level}`,
    folder,
    uses,
    activities,
    automation: {
      feature: key,
      keeperFeature: true,
      minimumLevel: level,
      ...extraAutomation
    },
    sourcePage: "1–10",
    sourceCustom: SOURCE,
    description: value
  });
}

function specialization({
  key,
  name,
  img,
  requirement,
  body,
  automation,
  specializationKey
}) {
  return keeperFeature({
    key,
    name,
    img,
    level: 1,
    folder: SPECIALIZATION_FOLDER,
    extraAutomation: {
      keeperSpecialization: specializationKey,
      specializationRequirement: requirement
    },
    description: description(body, automation)
  });
}

