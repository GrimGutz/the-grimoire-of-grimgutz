function guardianFeature({
  key,
  name,
  img,
  level,
  folder = MAIN_FOLDER,
  description,
  uses = null,
  activities = {},
  extraAutomation = {}
}) {
  return feature({
    key,
    name,
    img,
    level,
    requirements: `Страж ${level}`,
    folder,
    uses,
    activities,
    automation: {
      feature: key,
      guardianFeature: true,
      minimumLevel: level,
      ...extraAutomation
    },
    sourcePage: "1–5",
    sourceCustom: SOURCE,
    description
  });
}

