function juggernautFeature({
  key,
  name,
  img,
  level,
  description,
  activities = {},
  uses = null,
  effects = []
}) {
  return feature({
    key,
    name,
    img,
    level,
    requirements: `Джаггернаут ${level}`,
    folder: JUGGERNAUT_FOLDER,
    sourcePage: "1–5",
    sourceCustom: SOURCE,
    automation: {
      feature: key,
      juggernautFeature: true,
      minimumLevel: level
    },
    activities,
    uses,
    effects,
    description
  });
}

