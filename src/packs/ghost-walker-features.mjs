function description(body, automation) {
  return `
    ${body}
    <hr>
    <p><strong>Автоматизация Foundry:</strong> ${automation}</p>
  `;
}

function ghostWalkerFeature({
  key,
  name,
  img,
  level,
  description: value,
  uses = null,
  activities = {},
  effects = [],
  extraAutomation = {}
}) {
  return feature({
    key,
    name,
    img,
    level,
    requirements: `Призрачный Странник ${level}`,
    folder: MAIN_FOLDER,
    uses,
    activities,
    effects,
    automation: {
      feature: key,
      ghostWalkerFeature: true,
      minimumLevel: level,
      ...extraAutomation
    },
    sourcePage: "1–4",
    sourceCustom: SOURCE,
    description: value
  });
}

function longRestUse(max = "1") {
  return {
    max,
    spent: 0,
    recovery: [
      { period: "lr", type: "recoverAll" }
    ]
  };
}

