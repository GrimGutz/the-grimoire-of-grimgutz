function description(body, automation) {
  return `
    ${body}
    <hr>
    <p><strong>Автоматизация Foundry:</strong> ${automation}</p>
  `;
}

function shortRestUse(max = "1") {
  return {
    max,
    spent: 0,
    recovery: [
      { period: "sr", type: "recoverAll" },
      { period: "lr", type: "recoverAll" }
    ]
  };
}

function insectLordFeature({
  key,
  name,
  img,
  level,
  description: value,
  uses = null,
  activities = {},
  extraAutomation = {}
}) {
  return feature({
    key,
    name,
    img,
    level,
    requirements: `Владыка насекомых ${level}`,
    folder: MAIN_FOLDER,
    uses,
    activities,
    automation: {
      feature: key,
      insectLordFeature: true,
      minimumLevel: level,
      ...extraAutomation
    },
    sourcePage: "1–3",
    sourceCustom: SOURCE,
    description: value
  });
}

